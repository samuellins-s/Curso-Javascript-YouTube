/*

Utilizando IF/ELSE,
    verificar se uma cidade é grande ou pequena
    cidade grande possui mais de 300mil habitantes

*/

const habitantes = 60000

if (habitantes > 300000){
    console.log(`A sua cidade é GRANDE! Possui ${habitantes} habitantes!`)
} else {
    console.log(`A sua cidade é PEQUENA! Possui ${habitantes} habitantes! `)
}
